// Generate index.html (root timeline) and out/piiguard_demo.en.srt from
// script.json + assets/audio/timing.json. Scene visuals live in compositions/<id>.html;
// each scene slot = PRE + voice duration + POST (+ optional hold).
// Usage: node build_timeline.mjs
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = dirname(fileURLToPath(import.meta.url));
const script = JSON.parse(readFileSync(join(ROOT, 'script.json'), 'utf8'));
const timing = JSON.parse(readFileSync(join(ROOT, 'assets/audio/timing.json'), 'utf8'));

export const PRE = 0.35; // silence before the voice starts in each scene
const POST = 0.55; // breath after the voice ends
const HOLD = { s12: 2.5 }; // extra seconds on the closing frame

const r2 = (n) => Math.round(n * 100) / 100;
const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

let t = 0;
const scenes = script.scenes.map((s) => {
  const voice = timing[s.id];
  if (!voice) throw new Error(`missing TTS timing for ${s.id}; run narration/tts.py`);
  const slot = r2(PRE + voice.duration + POST + (HOLD[s.id] || 0));
  const scene = { ...s, start: r2(t), slot, voice };
  t += slot;
  return scene;
});
const total = r2(t);

// English subtitle cues: one line per cue. With as many lines as TTS sentences, follow the
// sentence boundaries; otherwise spread lines over the spoken span by character length.
const cues = [];
for (const s of scenes) {
  const sent = s.voice.sentences;
  const begin = sent[0].start;
  const end = sent[sent.length - 1].end;
  const base = s.start + PRE;
  if (sent.length === s.en.length) {
    s.en.forEach((line, i) => cues.push({ line, a: base + sent[i].start, b: base + sent[i].end }));
  } else {
    const chars = s.en.reduce((n, l) => n + l.length, 0);
    let cur = begin;
    for (const line of s.en) {
      const dur = ((end - begin) * line.length) / chars;
      cues.push({ line, a: base + cur, b: base + cur + dur });
      cur += dur;
    }
  }
}
cues.forEach((c, i) => {
  const next = cues[i + 1];
  c.a = r2(c.a);
  c.b = r2(next && next.a - c.b < 0.4 ? next.a - 0.02 : c.b + 0.15); // bridge short gaps
});

const sceneHosts = scenes
  .map(
    (s) => `      <div id="${s.id}" class="clip" data-composition-id="${s.id}" data-composition-src="compositions/${s.id}.html"
        data-start="${s.start}" data-duration="${s.slot}" data-track-index="0" data-width="1920" data-height="1080"></div>`,
  )
  .join('\n');
const voices = scenes
  .map(
    (s) => `      <audio id="vo-${s.id}" src="assets/audio/${s.id}.mp3" data-start="${r2(s.start + PRE)}"
        data-duration="${s.voice.duration}" data-track-index="1" data-volume="1"></audio>`,
  )
  .join('\n');
const subs = cues
  .map(
    (c, i) => `        <div id="sub-${i + 1}" class="clip sub" data-start="${c.a}" data-duration="${r2(c.b - c.a)}" data-track-index="0"><span>${esc(c.line)}</span></div>`,
  )
  .join('\n');
// Captions live in their own sub-composition: one caption track spanning the whole film.
writeFileSync(
  join(ROOT, 'compositions', 'captions.html'),
  `<!doctype html>
<!-- GENERATED by build_timeline.mjs from script.json (English subtitle lines). -->
<html>
  <head><meta charset="UTF-8" /></head>
  <body>
    <template>
      <link rel="stylesheet" href="assets/theme.css" />
      <style>
        #root { position: absolute; inset: 0; pointer-events: none; }
        #root .sub { position: absolute; left: 0; right: 0; bottom: 34px; display: flex; justify-content: center; }
        #root .sub span { max-width: 1500px; padding: 10px 26px; border-radius: 12px; background: rgba(8, 23, 51, 0.82);
          color: #f8fafc; font-family: "Be Vietnam Pro", sans-serif; font-weight: 600; font-size: 33px; line-height: 1.3; text-align: center; }
      </style>
      <div id="root" data-composition-id="captions" data-width="1920" data-height="1080">
${subs}
      </div>
      <script>
        const tl = gsap.timeline({ paused: true });
        window.__timelines["captions"] = tl;
      </script>
    </template>
  </body>
</html>
`,
);

// Inline the theme (fonts, tokens) so the renderer's static font check sees every @font-face.
const theme = readFileSync(join(ROOT, 'assets/theme.css'), 'utf8').replace(/url\("(fonts|brand)\//g, 'url("assets/$1/');

const html = `<!doctype html>
<!-- GENERATED by build_timeline.mjs from script.json + assets/audio/timing.json. Edit those, not this file. -->
<html lang="vi">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=1920, height=1080" />
    <script src="https://cdn.jsdelivr.net/npm/gsap@3.14.2/dist/gsap.min.js"></script>
    <style>
${theme}
      * { margin: 0; padding: 0; box-sizing: border-box; }
      html, body { margin: 0; width: 1920px; height: 1080px; overflow: hidden; background: #081733; }
      #root { position: relative; width: 100%; height: 100%; overflow: hidden; font-family: "Be Vietnam Pro", sans-serif; }
    </style>
  </head>
  <body>
    <div id="root" data-composition-id="main" data-start="0" data-duration="${total}" data-width="1920" data-height="1080">
${sceneHosts}
${voices}
      <div id="captions" class="clip" data-composition-id="captions" data-composition-src="compositions/captions.html" data-track-kind="captions"
        data-start="0" data-duration="${total}" data-track-index="2" data-width="1920" data-height="1080" style="z-index: 50"></div>
    </div>
    <script>
      const tl = gsap.timeline({ paused: true });
      window.__timelines["main"] = tl;
    </script>
  </body>
</html>
`;
writeFileSync(join(ROOT, 'index.html'), html);

const srtTime = (x) => {
  const ms = Math.round(x * 1000);
  const p = (n, w = 2) => String(n).padStart(w, '0');
  return `${p(Math.floor(ms / 3600000))}:${p(Math.floor(ms / 60000) % 60)}:${p(Math.floor(ms / 1000) % 60)},${p(ms % 1000, 3)}`;
};
mkdirSync(join(ROOT, 'out'), { recursive: true });
writeFileSync(
  join(ROOT, 'out', 'piiguard_demo.en.srt'),
  cues.map((c, i) => `${i + 1}\n${srtTime(c.a)} --> ${srtTime(c.b)}\n${c.line}\n`).join('\n'),
);

for (const s of scenes) console.log(`${s.id}  start ${s.start.toFixed(2)}  slot ${s.slot.toFixed(2)}  ${s.name}`);
console.log(`total ${total}s (${Math.floor(total / 60)}:${String(Math.round(total % 60)).padStart(2, '0')}), ${cues.length} subtitle cues`);
